        "# --- 1. Imports & Setup ---\n",
        "import pandas as pd\n",
        "import numpy as np\n",
        "from sklearn.model_selection import train_test_split\n",
        "from sklearn.linear_model import LinearRegression\n",
        "from sklearn.preprocessing import PolynomialFeatures\n",
        "from sklearn.ensemble import RandomForestRegressor\n",
        "from xgboost import XGBRegressor\n",
        "from sklearn.metrics import r2_score\n",
        "from IPython.display import display\n",
        "\n",
        "print(\"Libraries loaded successfully...\\n\")\n",
        "\n",
        "# --- 2. Load & Clean the Data ---\n",
        "url = \"https://raw.githubusercontent.com/dataprofessor/data/refs/heads/master/delaney_solubility_with_descriptors.csv\"\n",
        "df = pd.read_csv(url)\n",
        "\n",
        "# Round those lengthy decimals down to 2 places for a cleaner dataset\n",
        "df = df.round(2)\n",
        "\n",
        "# Separate the 4 clues (X) from the answer (y)\n",
        "y = df['logS']\n",
        "X = df.drop('logS', axis=1)\n",
        "\n",
        "# Split into Practice Homework (80%) and Final Exam (20%)\n",
        "X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=100)\n",
        "\n",
        "# --- 3. Define the Master Evaluation Tool ---\n",
        "def evaluate_model(model, X_train_data, X_test_data, model_name, tolerance=0.5):\n",
        "    # Train the model\n",
        "    model.fit(X_train_data, y_train)\n",
        "\n",
        "    # Generate predictions\n",
        "    y_pred_train = model.predict(X_train_data)\n",
        "    y_pred_test = model.predict(X_test_data)\n",
        "\n",
        "    # Calculate R² scores\n",
        "    train_r2 = r2_score(y_train, y_pred_train)\n",
        "    test_r2 = r2_score(y_test, y_pred_test)\n",
        "\n",
        "    # Calculate strict custom accuracy (±0.5)\n",
        "    errors = np.abs(np.array(y_test) - y_pred_test)\n",
        "    accuracy = (errors <= tolerance).sum() / len(y_test) * 100\n",
        "\n",
        "    # Return a dictionary so we can build a visual table\n",
        "    return {\n",
        "        \"Model\": model_name,\n",
        "        \"Train R² Score\": round(train_r2, 4),\n",
        "        \"Test R² Score\": round(test_r2, 4),\n",
        "        \"Custom Accuracy (±0.5)\": f\"{accuracy:.2f}%\"\n",
        "    }\n",
        "\n",
        "# --- 4. Initialize the Models ---\n",
        "lr = LinearRegression()\n",
        "rf = RandomForestRegressor(n_estimators=100, random_state=100)\n",
        "xgb = XGBRegressor(random_state=100)\n",
        "\n",
        "# For Polynomial Regression, we have to transform the data first\n",
        "poly = PolynomialFeatures(degree=2)\n",
        "X_train_poly = poly.fit_transform(X_train)\n",
        "X_test_poly = poly.transform(X_test)\n",
        "poly_lr = LinearRegression()\n",
        "\n",
        "# --- 5. Run the Pipeline and Display the Visual Table ---\n",
        "# Gather all the results into a list\n",
        "all_results = [\n",
        "    evaluate_model(lr, X_train, X_test, \"Linear Regression\"),\n",
        "    evaluate_model(poly_lr, X_train_poly, X_test_poly, \"Polynomial Reg.\"),\n",
        "    evaluate_model(rf, X_train, X_test, \"Random Forest\"),\n",
        "    evaluate_model(xgb, X_train, X_test, \"XGBoost\")\n",
        "]\n",
        "\n",
        "# Convert the list into a Pandas DataFrame (This fixes your NameError!)\n",
        "results_df = pd.DataFrame(all_results)\n",
        "\n",
        "# Display the final, color-coded table\n",
        "print(\"### Final Model Performance Summary (Tolerance = 0.5)\\n\")\n",
        "display(results_df.style.background_gradient(cmap='Greens'))"
